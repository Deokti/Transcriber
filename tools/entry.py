"""Точка входа для собранного приложения.

PyInstaller хочет отдельный файл-скрипт, а не модуль пакета. Здесь только
запуск: вся логика в app/main.py, как и при запуске из исходников.
"""
import multiprocessing
import sys

if __name__ == "__main__":
    # Служебные процессы multiprocessing (сторож ресурсов, форк-сервер)
    # запускаются командой «интерпретатор, выполни вот этот код». В собранном
    # виде вместо интерпретатора запускается сама программа, ключ -c она не
    # понимает — и у человека открывается второе окно. PyInstaller умеет
    # разобрать такой запуск, но только когда его об этом попросят: без этой
    # строки подмена лежит без дела.
    #
    # Замок, из-за которого сторож вообще заводится, создаёт tqdm — тот, через
    # который видно проценты скачивания модели.
    multiprocessing.freeze_support()

    from app.main import main

    sys.exit(main())
